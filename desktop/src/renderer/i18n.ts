export type UiLanguage = "pt-BR" | "en";

const LANGUAGE_STORAGE_KEY = "kre.ui-language";

export function resolveInitialLanguage(
  savedLanguage: string | null,
  systemLanguage: string,
): UiLanguage {
  if (savedLanguage === "pt-BR" || savedLanguage === "en") return savedLanguage;
  return systemLanguage.trim().toLowerCase().startsWith("en") ? "en" : "pt-BR";
}

export function loadLanguagePreference(storage: Pick<Storage, "getItem">, systemLanguage: string): UiLanguage {
  return resolveInitialLanguage(storage.getItem(LANGUAGE_STORAGE_KEY), systemLanguage);
}

export function saveLanguagePreference(storage: Pick<Storage, "setItem">, language: UiLanguage): void {
  storage.setItem(LANGUAGE_STORAGE_KEY, language);
}

export function getUiLocale(language: UiLanguage): string {
  return language === "en" ? "en-US" : "pt-BR";
}

